"""Markdown and HTML reports of an audit.

Both render the same reporting.View as the SARIF export, so the three formats
list the same failing rules at the same locations. The Markdown is GitHub
flavoured and renders in a repository, a pull request and a job summary. The
HTML is one self-contained file: inline CSS, no fonts, scripts or images from
anywhere, light and dark styles chosen by prefers-color-scheme, and every value
taken from the project escaped.

The gate decision
-----------------
The reports show the gate's own decision, from gate.clears. The deterministic
conditions come first, so a project with a critical failure or a score under 90
is decided without building anything. A project that meets both is asked the
third condition, the model's estimate, which needs the build check: Render's
build command run in Docker on a read-only copy of the project. Where Docker is
not available the gate stays shut and the reason says no estimate could be
produced, exactly as prodpilot_deploy would decide.
"""

from __future__ import annotations

import html
from dataclasses import dataclass

from prodpilot import __version__, gate
from prodpilot.blueprint import Priority
from prodpilot.reaudit import Reaudit
from prodpilot.reporting import DOCS, Item, View


@dataclass(frozen=True)
class Decision:
    ready: bool
    reason: str

    @property
    def label(self) -> str:
        return "ready to deploy" if self.ready else "not ready"


def decide(view: View) -> Decision:
    """The gate's decision for the audited project, as prodpilot_deploy reaches it."""
    report = view.report
    result = Reaudit(project=report.project, report=report, root=str(view.root),
                     reason="" if report.results else report.detection.reason)
    ready, reason = gate.clears(result)
    return Decision(ready, reason)


def grouped(view: View) -> list[tuple[str, list[Item]]]:
    """Failing rules grouped by priority, P0 first, empty groups left out."""
    out = []
    for priority in Priority:
        items = [i for i in view.items if i.result.priority is priority]
        if items:
            out.append((priority.value, items))
    return out


# --------------------------------------------------------------------------
# Markdown
# --------------------------------------------------------------------------


def cell(text: str) -> str:
    """Text made safe for one Markdown table cell."""
    flat = " ".join(str(text).split())
    return html.escape(flat, quote=False).replace("|", "\\|")


def code(text: str) -> str:
    """A path in a cell. Backticks would end the span, so they are escaped first."""
    return "<code>" + cell(text).replace("`", "&#96;") + "</code>"


def to_markdown(view: View, decision: Decision) -> str:
    report = view.report
    lines = [
        f"# ProdPilot report: {cell(view.project)}",
        "",
        f"**Score:** {report.score}/100, {report.band.value}  ",
        f"**Gate:** {decision.label}. {cell(decision.reason)}  ",
        f"**Stack:** {cell(report.stack.value)}  ",
        f"**Failing rules:** {len(view.items)}, of which {len(report.blockers)} critical",
        "",
    ]
    if view.notices:
        lines += ["## Notices", ""]
        lines += [f"- {cell(n)}" for n in view.notices]
        lines.append("")

    lines += ["## Failing rules by priority", "", "| Priority | Failing |", "| --- | ---: |"]
    lines += [f"| {p} | {n} |" for p, n in view.failing_by_priority().items()]
    lines += ["", "## Failing rules by domain", "", "| Domain | Failing |", "| --- | ---: |"]
    by_domain = view.failing_by_domain()
    if by_domain:
        lines += [f"| {cell(d)} | {n} |" for d, n in by_domain.items()]
    else:
        lines.append("| none | 0 |")
    lines.append("")

    lines += ["## Failing rules", ""]
    if not view.items:
        lines += ["No rule is failing.", ""]
    for priority, items in grouped(view):
        lines += [f"### {priority} ({len(items)})", "",
                  "| Rule | Requirement | Finding | Location | Fix type |",
                  "| --- | --- | --- | --- | --- |"]
        for item in items:
            where = "<br>".join(code(w.label()) for w in item.locations)
            lines.append(f"| {cell(item.rule_id)} | {cell(item.result.rule.description)} | "
                         f"{cell(item.message)} | {where} | {cell(item.result.fix_type.value)} |")
        lines.append("")
    lines.append(f"Generated by ProdPilot {__version__}. {DOCS}")
    return "\n".join(lines) + "\n"


