def esc(text: object) -> str:
    return html.escape(str(text), quote=True)


def to_html(view: View, decision: Decision) -> str:
    report = view.report
    state = "ready" if decision.ready else "shut"
    parts = [
        "<!doctype html>",
        '<html lang="en">',
        "<head>",
        '<meta charset="utf-8">',
        '<meta name="viewport" content="width=device-width, initial-scale=1">',
        '<meta name="color-scheme" content="light dark">',
        f"<title>ProdPilot report: {esc(view.project)}</title>",
        f"<style>{STYLE}</style>",
        "</head>",
        "<body>",
        "<main>",
        f"<h1>ProdPilot report: {esc(view.project)}</h1>",
        "<dl>",
        f"<dt>Score</dt><dd>{report.score}/100, {esc(report.band.value)}</dd>",
        f'<dt>Gate</dt><dd><span class="{state}">{esc(decision.label)}</span>. '
        f"{esc(decision.reason)}</dd>",
        f"<dt>Stack</dt><dd>{esc(report.stack.value)}</dd>",
        f"<dt>Failing rules</dt><dd>{len(view.items)}, of which "
        f"{len(report.blockers)} critical</dd>",
        "</dl>",
    ]
    if view.notices:
        parts.append("<h2>Notices</h2>")
        parts.append('<ul class="notices">' + "".join(f"<li>{esc(n)}</li>" for n in view.notices)
                     + "</ul>")

    def counts(title: str, head: str, rows: dict[str, int]) -> None:
        parts.append(f"<h2>{esc(title)}</h2>")
        body = "".join(f'<tr><td>{esc(k)}</td><td class="num">{v}</td></tr>'
                       for k, v in rows.items()) or '<tr><td>none</td><td class="num">0</td></tr>'
        parts.append(f'<div class="wrap"><table><thead><tr><th>{esc(head)}</th>'
                     f'<th>Failing</th></tr></thead><tbody>{body}</tbody></table></div>')

    counts("Failing rules by priority", "Priority", view.failing_by_priority())
    counts("Failing rules by domain", "Domain", view.failing_by_domain())

    parts.append("<h2>Failing rules</h2>")
    if not view.items:
        parts.append("<p>No rule is failing.</p>")
    for priority, items in grouped(view):
        parts.append(f"<h3>{esc(priority)} ({len(items)})</h3>")
        rows = []
        for item in items:
            where = "<br>".join(f"<code>{esc(w.label())}</code>" for w in item.locations)
            rows.append(
                f'<tr data-rule="{esc(item.rule_id)}">'
                f'<td>{esc(item.rule_id)}<br><span class="level {esc(item.level)}">'
                f"{esc(item.level)}</span></td>"
                f"<td>{esc(item.result.rule.description)}</td>"
                f"<td>{esc(item.message)}</td>"
                f"<td>{where}</td>"
                f"<td>{esc(item.result.fix_type.value)}</td></tr>")
        parts.append('<div class="wrap"><table><thead><tr><th>Rule</th><th>Requirement</th>'
                     "<th>Finding</th><th>Location</th><th>Fix type</th></tr></thead>"
                     f"<tbody>{''.join(rows)}</tbody></table></div>")
    parts += [f"<footer>Generated by ProdPilot {esc(__version__)}. {esc(DOCS)}</footer>",
              "</main>", "</body>", "</html>"]
    return "\n".join(parts) + "\n"
